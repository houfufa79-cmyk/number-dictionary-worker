// Bundles the standalone page (index.html) and the Worker's HTML module (src/page.js).
// Source of truth: src/template.html + src/raw-dictionary.js (extracted from 51dic.csv) + src/decode.js
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The browser <script> is not a module, so strip ES import/export syntax and
// inline the dictionary module before the decoder that references it.
function toInlineScript(path) {
  return readFileSync(path, 'utf8')
    .replace(/^import\s+[^;]+;\s*$/gm, '')   // drop import statements
    .replace(/^export\s+/gm, '')             // drop export keywords
    .replace(/<\/script/gi, '<\\/script');   // guard the inline script tag
}

const dictionarySource = toInlineScript(join(root, 'src', 'raw-dictionary.js'));
const decodeSource = toInlineScript(join(root, 'src', 'decode.js'));
const InlineLogic = dictionarySource + '\n' + decodeSource;

const template = readFileSync(join(root, 'src', 'template.html'), 'utf8');
const PLACEHOLDER = '/*__DECODE_JS__*/';
if (!template.includes(PLACEHOLDER)) {
  throw new Error('template.html is missing the decode injection placeholder');
}

const html = template.replace(PLACEHOLDER, InlineLogic);

// 1. Standalone page — open directly in a browser or host anywhere.
writeFileSync(join(root, 'index.html'), html, 'utf8');

// 2. Worker module — safe string literal consumed by src/index.js.
const pageModule =
  '// Generated by scripts/build.mjs — do not edit by hand.\n' +
  'export const PAGE_HTML = ' + JSON.stringify(html) + ';\n';
writeFileSync(join(root, 'src', 'page.js'), pageModule, 'utf8');

console.log('Built index.html and src/page.js');
